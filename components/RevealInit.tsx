"use client";

import { useEffect } from "react";

/**
 * Progressive enhancement for the `.reveal` class: content is fully visible
 * without JavaScript, and only gets the entrance animation once this component
 * confirms the browser can run it. Respects prefers-reduced-motion.
 */
export function RevealInit() {
  useEffect(() => {
    const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (reduced || !("IntersectionObserver" in window)) return;

    const root = document.documentElement;
    root.classList.add("js-reveal");

    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-in");
            observer.unobserve(entry.target);
          }
        }
      },
      { rootMargin: "0px 0px -8% 0px", threshold: 0.05 },
    );

    const scan = () => {
      for (const element of document.querySelectorAll(".reveal:not(.is-in)")) {
        observer.observe(element);
      }
    };

    scan();
    const mutation = new MutationObserver(scan);
    mutation.observe(document.body, { childList: true, subtree: true });

    return () => {
      observer.disconnect();
      mutation.disconnect();
      root.classList.remove("js-reveal");
    };
  }, []);

  return null;
}
